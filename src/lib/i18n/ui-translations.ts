/** Packs saisis à la main (sans fusion anglaise) — pour l'interface bilingue. */
export const UI_TRANSLATIONS_EXPLICIT: Record<string, UiTranslationPack> = {};

/** Complète les packs partiels avec l'anglais pour couvrir toute l'application. */
const EN_REFERENCE = UI_TRANSLATIONS.en as UiTranslationPack;
for (const [lang, pack] of Object.entries(UI_TRANSLATIONS)) {
	if (lang === 'fr' || lang === 'en') continue;
	UI_TRANSLATIONS_EXPLICIT[lang] = { ...pack };
	UI_TRANSLATIONS[lang] = { ...EN_REFERENCE, ...pack };
}

export function getUiTranslation(key: UiKey, lang: string): string | undefined {
	if (lang === 'fr') return UI_TRANSLATIONS.fr[key];
	if (lang === 'en') return UI_TRANSLATIONS.en[key];
	const explicit = UI_TRANSLATIONS_EXPLICIT[lang]?.[key];
	if (explicit) return explicit;
	return UI_TRANSLATIONS.en[key];
}

/** Ligne secondaire bilingue : pack installé ; pas de repli anglais pour les langues prioritaires. */
export function getBilingualSecondaryTranslation(key: UiKey, lang: string): string | undefined {
	if (lang === 'fr') return undefined;
	if (lang === 'en') return UI_TRANSLATIONS.en[key];
	const fromPack = getRuntimeUiTranslation(key, lang);
	if (fromPack) return fromPack;
	if (isPriorityLanguage(lang)) return undefined;
	return UI_TRANSLATIONS_EXPLICIT[lang]?.[key];
}
