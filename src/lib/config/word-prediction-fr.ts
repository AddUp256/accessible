/** Préfixes multi-mots pour bigrammes composés (ex. « je suis »). */
export function nextWordKey(previousWord: string, wordBefore?: string | null): string {
	const prev = previousWord.toLowerCase();
	if (wordBefore) {
		const compound = `${wordBefore.toLowerCase()}_${prev}`;
		if (compound in NEXT_WORD_SUGGESTIONS) return compound;
	}
	return prev;
}
